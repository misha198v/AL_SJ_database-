const results=[];
function check(condition,label) {assert.ok(condition,label); checks++; results.push({label,passed:true}); console.log('PASS:',label);}
async function axe(page,label) {
  await page.addScriptTag({path:path.resolve(__dirname,'../tests/vendor/axe.min.js')});
  const report=await page.evaluate(async()=>await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa']}}));
  fs.writeFileSync(path.join(out,label+'-axe.json'),JSON.stringify(report,null,2));
  if(report.violations.length) await page.screenshot({path:path.join(out,label+'-failure.png'),fullPage:true});
  check(report.violations.length===0,label+' automated accessibility ('+report.violations.map(v=>v.id).join(',')+')');
}
async function login(page,phone) {
  await page.goto(base+'/login/');
  await page.locator('#phone').fill(phone);
  await page.locator('#password').fill(password);
  await Promise.all([page.waitForURL(url=>!url.pathname.endsWith('/login/')),page.getByRole('button',{name:'Sign in to workspace'}).click()]);
}
