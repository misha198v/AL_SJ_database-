import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
tokens = json.loads((ROOT/'core/static/core/tokens.json').read_text())
lines = ['/* Generated by scripts/generate_tokens.py. Do not hand-edit. */', ':root {']
for group,prefix in [('colors','color'),('fonts','font'),('radii','radius'),('spacing','space')]:
    lines += [f'  --{prefix}-{key}: {value};' for key,value in tokens[group].items()]
lines += ['}']
(ROOT/'core/static/core/tokens.css').write_text('\n'.join(lines)+'\n',encoding='utf-8')
